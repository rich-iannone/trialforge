"""Write the license texts of the Rust crates compiled into the Python extension module.

MIT and Apache-2.0 both require each crate's license text (with its copyright lines) and, for
Apache-2.0, its NOTICE file to go with the binary. This script writes them to
`python/THIRD_PARTY_LICENSES.txt`, which the wheels and the sdist ship next to `LICENSE` and
`NOTICE.md`:

- the crates are the normal (not build, dev or proc-macro) dependencies of `python/Cargo.toml`
  on each target the wheels are built for, as locked in `Cargo.lock`,
- a crate that offers a choice including MIT is used under MIT, otherwise under Apache-2.0; any
  other license stops the script, so a new one gets a deliberate look,
- each crate's own license, NOTICE and COPYRIGHT files are copied from its package, and identical
  texts are printed once,
- the NOTICE files of the crates used under Apache-2.0 must also be quoted in `NOTICE.md`.

Run from the repository root after any change to `Cargo.lock` (needs the crates in the cargo
cache, or network access):

    python scripts/third_party_licenses.py           # rewrite the file
    python scripts/third_party_licenses.py --check   # fail if it is out of date (CI)
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "python" / "Cargo.toml"
OUTPUT = ROOT / "python" / "THIRD_PARTY_LICENSES.txt"

# The wheel targets in .github/workflows/python-dist.yml.
TARGETS = [
    "x86_64-unknown-linux-gnu",
    "aarch64-unknown-linux-gnu",
    "x86_64-apple-darwin",
    "aarch64-apple-darwin",
    "x86_64-pc-windows-msvc",
]

# Preference among the alternatives of an `OR` license, and the licenses we know how to honor.
PREFERENCE = ["MIT", "Apache-2.0"]

# Words that identify a license file's license from its name, and a phrase from its text that
# confirms a generically named file (LICENSE, LICENSE.txt, COPYING) holds that license.
NAME_HINT = {"MIT": "MIT", "Apache-2.0": "APACHE"}
TEXT_HINT = {"MIT": "Permission is hereby granted", "Apache-2.0": "Apache License"}
GENERIC = {"LICENSE", "LICENSE.TXT", "LICENSE.MD", "LICENCE", "COPYING"}
NOTICES = ("NOTICE", "COPYRIGHT")

HEADER = """\
Third-party licenses for the trialforge Python extension module (trialforge._core)

The extension module compiles in the Rust crates listed below. Where a crate offers a choice of
licenses that includes MIT, trialforge uses it under MIT; otherwise it uses it under the license
given. The license texts, copyright lines and NOTICE files that the crates ship follow the table.

The module also contains the Rust standard library, licensed under the MIT License or the Apache
License 2.0; its notices are at https://github.com/rust-lang/rust/blob/master/COPYRIGHT.

This file is generated by scripts/third_party_licenses.py from Cargo.lock; don't edit it by hand.
"""

RULE = "=" * 100


@dataclass
class Crate:
    name: str
    version: str
    declared: str
    used: list[str]
    authors: list[str]
    files: list[tuple[str, str]] = field(default_factory=list)  # (file name, text)
    missing: list[str] = field(default_factory=list)  # licenses with no file in the package


def cargo(*args: str) -> str:
    return subprocess.run(
        ["cargo", *args, "--locked", "--manifest-path", str(MANIFEST)],
        check=True,
        capture_output=True,
        text=True,
        cwd=ROOT,
    ).stdout


def compiled_in() -> set[tuple[str, str]]:
    """The (name, version) of every crate linked into the extension on some wheel target."""
    crates: set[tuple[str, str]] = set()
    for target in TARGETS:
        out = cargo(
            "tree",
            "-e",
            "normal,no-proc-macro",
            "--target",
            target,
            "--prefix",
            "none",
            "--format",
            "{p}",
        )
        for line in out.splitlines():
            name, version = line.split()[:2]
            crates.add((name, version.removeprefix("v")))
    return crates


def choose(expression: str) -> list[str]:
    """The licenses we use a crate under, from its SPDX expression."""
    if "(" in expression or "WITH" in expression:
        raise SystemExit(f"unsupported license expression: {expression}")
    if " OR " in expression and " AND " not in expression:
        options = expression.split(" OR ")
        for license_id in PREFERENCE:
            if license_id in options:
                return [license_id]
        raise SystemExit(f"no supported license in: {expression}")
    if " OR " in expression:
        raise SystemExit(f"unsupported license expression: {expression}")
    parts = expression.split(" AND ")
    for part in parts:
        if part not in PREFERENCE:
            raise SystemExit(f"unsupported license: {part} (in {expression})")
    return parts


def read(path: Path) -> str:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    return "\n".join(line.rstrip() for line in text.split("\n")).strip("\n")


def license_files(crate: Crate, directory: Path) -> None:
    """Add the crate's files for the licenses it's used under, and its notices."""
    names = sorted(p.name for p in directory.iterdir() if p.is_file())
    chosen: list[str] = []
    for license_id in crate.used:
        specific = [n for n in names if n.upper().startswith(("LICENSE", "LICENCE"))]
        specific = [n for n in specific if NAME_HINT[license_id] in n.upper()]
        generic = [
            n
            for n in names
            if n.upper() in GENERIC and TEXT_HINT[license_id] in read(directory / n)
        ]
        found = specific or generic
        if not found:
            crate.missing.append(license_id)
        chosen += [n for n in found if n not in chosen]
    chosen += [n for n in names if n.upper().startswith(NOTICES) and n not in chosen]
    crate.files = [(n, read(directory / n)) for n in chosen]


def collect() -> list[Crate]:
    wanted = compiled_in()
    metadata = json.loads(cargo("metadata", "--format-version", "1"))
    crates: list[Crate] = []
    for package in metadata["packages"]:
        key = (package["name"], package["version"])
        if key not in wanted or package["source"] is None:  # workspace crates are ours
            continue
        crate = Crate(
            name=package["name"],
            version=package["version"],
            declared=package["license"],
            used=choose(package["license"]),
            authors=package["authors"],
        )
        license_files(crate, Path(package["manifest_path"]).parent)
        crates.append(crate)
    crates.sort(key=lambda c: (c.name, c.version))
    if len(crates) != len({k for k in wanted if not k[0].startswith("trialforge")}):
        raise SystemExit("some compiled-in crates were not found in cargo metadata")
    return crates


def render(crates: list[Crate]) -> str:
    # Each distinct text once, in the order the crates first use it.
    groups: dict[str, list[str]] = {}
    for crate in crates:
        for name, text in crate.files:
            groups.setdefault(text, []).append(f"{crate.name} {crate.version} ({name})")

    # A crate that ships no file for its license is attached to that license's most common text.
    for crate in crates:
        for license_id in crate.missing:
            texts = Counter(
                text
                for c in crates
                for name, text in c.files
                if license_id in c.used and TEXT_HINT[license_id] in text
                if NAME_HINT[license_id] in name.upper() or name.upper() in GENERIC
            )
            if not texts:
                raise SystemExit(f"no {license_id} text for {crate.name}, which ships none")
            standard = texts.most_common(1)[0][0]
            groups[standard].append(
                f"{crate.name} {crate.version} (ships no license file; {license_id} applies)"
            )

    rows = [("Crate", "Version", "License", "Used under")]
    rows += [(c.name, c.version, c.declared, " AND ".join(c.used)) for c in crates]
    widths = [max(len(row[i]) for row in rows) for i in range(4)]
    table = ["  ".join(row[i].ljust(widths[i]) for i in range(4)).rstrip() for row in rows]
    table.insert(1, "  ".join("-" * w for w in widths))

    authors = [f"{c.name}: {', '.join(c.authors)}" for c in crates if c.authors]

    parts = [HEADER, "\n".join(table), "", "Authors, as the crates' manifests give them:", ""]
    parts += [f"  {line}" for line in authors]
    for text, users in groups.items():
        parts += ["", RULE, "Used by:", *[f"  {user}" for user in users], RULE, "", text]
    return "\n".join(parts) + "\n"


def check_notices(crates: list[Crate]) -> None:
    """Apache-2.0 asks for each NOTICE to be carried on; NOTICE.md quotes them, indented."""
    notice = (ROOT / "NOTICE.md").read_text(encoding="utf-8")
    for crate in crates:
        if "Apache-2.0" not in crate.used:
            continue
        for name, text in crate.files:
            quoted = "\n".join(f"    {line}".rstrip() for line in text.split("\n"))
            if name.upper().startswith("NOTICE") and quoted not in notice:
                raise SystemExit(
                    f"NOTICE.md doesn't quote {crate.name} {crate.version}'s {name}; add it, "
                    "indented four spaces, under 'Rust crates in the compiled extension'"
                )


def main() -> None:
    crates = collect()
    check_notices(crates)
    content = render(crates)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            raise SystemExit(
                f"{OUTPUT.relative_to(ROOT)} is out of date with Cargo.lock; "
                "run `python scripts/third_party_licenses.py`"
            )
        return
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
